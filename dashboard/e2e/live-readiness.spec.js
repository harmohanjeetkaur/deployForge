import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('live backend: readiness, real GHCR verification, both confirmations cancel without any POST', async ({ page }) => {
  test.skip(process.env.DEPLOYFORGE_READ_ONLY_UI !== '1', 'Opt-in live browser GET-only verification')
  let prohibited = 0
  await page.route('**/api/**', async route => {
    if (route.request().method() !== 'GET') { prohibited++; await route.abort(); return }
    await route.continue()
  })
  await page.goto('/')
  await page.getByRole('link', { name: 'Deployments', exact: true }).click()
  await expect(page.locator('.backend-readiness')).toContainText('Execution enabled · docker-desktop')
  await expect(page.getByRole('alert')).toHaveCount(0)
  await expect(page.getByRole('status')).toHaveText('Rollback healthy')
  await expect(page.locator('.step-complete')).toHaveCount(5)
  await page.getByRole('button', { name: 'Deploy New Version', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Deploy Version', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Verify Image Availability', exact: true }).click()
  await expect(page.getByText('✓ Image verified in GHCR', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Preview Version Change', exact: true }).click()
  await expect(page.locator('.preview-side.current')).toContainText('210426be6d6da6c2e16f234db410f83a0c98bbd2')
  await expect(page.locator('.preview-side.target')).toContainText('5b6d2c0589ab9e4a6dedbde072a95ccf124921aa')
  await expect(page.locator('#gitops-requirements')).toContainText('Authorize Deployment')
  const token = (await readFile(process.env.HOME + '/.deployforge-secrets/deploy-token', 'utf8')).trim()
  if (!token) throw new Error('Private credential is unavailable')
  await page.locator('#deployment-token').fill(token)
  await page.getByRole('button', { name: 'Deploy Version', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Confirm Deployment', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('button', { name: 'Select revision 6 for rollback', exact: true }).click()
  await expect(page.getByTestId('rollback-action')).toHaveText('Rollback to Revision 6')
  await expect(page.getByTestId('rollback-action')).toBeDisabled()
  await page.getByRole('button', { name: 'Verify Image Availability', exact: true }).click()
  await expect(page.getByText('✓ Image verified in GHCR', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Preview Version Change', exact: true }).click()
  await page.getByTestId('rollback-action').click()
  await expect(page.getByRole('heading', { name: 'Confirm Rollback', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('button', { name: 'Refresh Versions', exact: true }).click()
  await expect(page.locator('.version-info')).toContainText('Rollback eligible: Yes')
  await page.getByRole('link', { name: 'Overview', exact: true }).click()
  await page.getByRole('link', { name: 'Deployments', exact: true }).click()
  await expect(page.locator('#deployment-token')).toHaveValue('')
  expect(await page.evaluate(() => localStorage.length + sessionStorage.length)).toBe(0)
  expect(prohibited).toBe(0)
})
